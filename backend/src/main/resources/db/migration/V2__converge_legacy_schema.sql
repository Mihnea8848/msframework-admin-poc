-- Brings databases created by older versions of the app (Hibernate ddl-auto=update, before
-- Flyway) in line with V1. FlywayConfig baselines such databases at version 1, so this is the
-- first script they run. Every step is idempotent and changes nothing on a database created
-- by V1.
--
-- What older versions left behind:
--   * before the RBAC change: a users.role varchar column, no role / role_permissions /
--     user_roles tables, users without any role;
--   * the first versions: NOT NULL on users.full_name, phone, password, status, department_id
--     and a users.joined_date column;
--   * the RBAC version: role.name without NOT NULL;
--   * tables and columns added later (password_reset_tokens, api_keys.key_hash, ...).

-- Helpers, dropped again at the end. pg_temp keeps them private to this session.

-- Makes a column nullable or NOT NULL, only when it is not already.
CREATE FUNCTION pg_temp.set_nullable(tbl text, col text, nullable boolean) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = tbl AND column_name = col
                 AND (is_nullable = 'YES') <> nullable) THEN
        EXECUTE format('ALTER TABLE %I ALTER COLUMN %I %s NOT NULL',
                       tbl, col, CASE WHEN nullable THEN 'DROP' ELSE 'SET' END);
    END IF;
END $$;

-- Adds a constraint under its V1 name. If the same kind of constraint already exists on the
-- same columns under another name, it is renamed instead of duplicated.
CREATE FUNCTION pg_temp.ensure_constraint(tbl text, con text, kind "char", cols text[], ddl text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    existing text;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint
               WHERE conrelid = to_regclass(quote_ident(tbl)) AND conname = con) THEN
        RETURN;
    END IF;
    SELECT c.conname INTO existing
    FROM pg_constraint c
    WHERE c.conrelid = to_regclass(quote_ident(tbl))
      AND c.contype = kind
      AND (SELECT array_agg(a.attname::text ORDER BY a.attname)
           FROM unnest(c.conkey) AS k(attnum)
           JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum)
          = (SELECT array_agg(x ORDER BY x) FROM unnest(cols) AS x)
    LIMIT 1;
    IF existing IS NOT NULL THEN
        EXECUTE format('ALTER TABLE %I RENAME CONSTRAINT %I TO %I', tbl, existing, con);
        RAISE NOTICE 'Renamed constraint %.% to %', tbl, existing, con;
    ELSE
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', tbl, con, ddl);
    END IF;
END $$;

