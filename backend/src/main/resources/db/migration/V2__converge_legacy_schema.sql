-- 3. Data.

-- The first versions stored a join date; keep it as created_at.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'users'
                 AND column_name = 'joined_date') THEN
        EXECUTE 'UPDATE users SET created_at = joined_date::timestamp
                 WHERE created_at IS NULL AND joined_date IS NOT NULL';
        ALTER TABLE users DROP COLUMN joined_date;
        RAISE NOTICE 'Moved users.joined_date into created_at and dropped it';
    END IF;
END $$;

UPDATE users SET status = 'Active' WHERE status IS NULL OR btrim(status) = '';
UPDATE users SET created_at = now() WHERE created_at IS NULL;
UPDATE users SET password_changed_at = created_at WHERE password_changed_at IS NULL;

-- Users without a role. Before RBAC the role was a users.role varchar: map it to the built-in
-- role with the same name (case-insensitive), anything else to MEMBER, then drop the old
-- column. The built-in role rows are created first when needed (name only: DatabaseSeeder
-- syncs their permissions on start-up).
DO $$
DECLARE
    legacy_column boolean;
    assigned integer := 0;
BEGIN
    legacy_column := EXISTS (SELECT 1 FROM information_schema.columns
                             WHERE table_schema = current_schema() AND table_name = 'users'
                               AND column_name = 'role');

    IF EXISTS (SELECT 1 FROM users u
               WHERE NOT EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = u.id)) THEN
        INSERT INTO role (name)
        SELECT v.name
        FROM (VALUES ('ADMIN'), ('MANAGER'), ('MEMBER'), ('VIEWER')) AS v(name)
        WHERE NOT EXISTS (SELECT 1 FROM role r WHERE r.name = v.name);

        IF legacy_column THEN
            EXECUTE $sql$
                INSERT INTO user_roles (user_id, role_id)
                SELECT u.id, COALESCE(r.id, m.id)
                FROM users u
                JOIN role m ON m.name = 'MEMBER'
                LEFT JOIN role r ON r.name = upper(btrim(u.role))
                  AND r.name IN ('ADMIN', 'MANAGER', 'MEMBER', 'VIEWER')
                WHERE NOT EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = u.id)
            $sql$;
        ELSE
            INSERT INTO user_roles (user_id, role_id)
            SELECT u.id, m.id
            FROM users u
            JOIN role m ON m.name = 'MEMBER'
            WHERE NOT EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = u.id);
        END IF;
        GET DIAGNOSTICS assigned = ROW_COUNT;
        RAISE NOTICE 'Assigned a role to % users that had none', assigned;
    END IF;

    IF legacy_column THEN
        ALTER TABLE users DROP COLUMN role;
        RAISE NOTICE 'Dropped the legacy users.role column';
    END IF;
END $$;

