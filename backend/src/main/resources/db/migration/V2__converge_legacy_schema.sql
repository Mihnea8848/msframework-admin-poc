-- Databases created by Hibernate carry a CHECK listing every permission name. Permissions are
-- validated by the application and written only by the seeder, and that CHECK would need a new
-- migration for every new permission, so remove it (whatever name it got).
DO $$
DECLARE c record;
BEGIN
    FOR c IN
        SELECT con.conname
        FROM pg_constraint con
        JOIN pg_class rel ON rel.oid = con.conrelid
        WHERE rel.relname = 'role_permissions' AND rel.relnamespace = current_schema()::regnamespace
          AND con.contype = 'c'
    LOOP
        EXECUTE format('ALTER TABLE role_permissions DROP CONSTRAINT %I', c.conname);
    END LOOP;
END
$$;

