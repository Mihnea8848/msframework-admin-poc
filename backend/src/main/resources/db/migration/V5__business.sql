-- Business domain: budgets, expenses with approvals, goals and KPI check-ins, and scoped API keys
-- for the metric ingest endpoint. Money is numeric(14,2) plus an ISO 4217 code; the organisation
-- uses one currency (app.finance.currency, EUR by default) and nothing is converted.
-- Never edit this file once applied. Add a new V<n>__description.sql instead.

-- API keys get scopes (space separated, e.g. 'ingest:checkins'). Existing keys get none, so
-- they keep doing exactly what they did before (nothing that needs a scope).
ALTER TABLE api_keys ADD COLUMN scopes character varying(255) NOT NULL DEFAULT '';

CREATE TABLE expense_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name character varying(60) NOT NULL,
    description character varying(255),
    active boolean NOT NULL DEFAULT true,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT expense_categories_pkey PRIMARY KEY (id),
    CONSTRAINT uk_expense_categories_name UNIQUE (name)
);

