-- One budget line per department, quarter and category.
CREATE TABLE budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    department_id bigint NOT NULL,
    category_id bigint NOT NULL,
    fiscal_year integer NOT NULL,
    fiscal_quarter integer NOT NULL,
    amount numeric(14, 2) NOT NULL,
    currency character varying(3) NOT NULL,
    notes character varying(255),
    created_by character varying(255),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT budgets_pkey PRIMARY KEY (id),
    CONSTRAINT uk_budgets_line UNIQUE (department_id, category_id, fiscal_year, fiscal_quarter),
    CONSTRAINT ck_budgets_quarter CHECK (fiscal_quarter BETWEEN 1 AND 4),
    CONSTRAINT ck_budgets_year CHECK (fiscal_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_budgets_amount CHECK (amount >= 0),
    CONSTRAINT fk_budgets_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_budgets_category FOREIGN KEY (category_id) REFERENCES expense_categories (id)
);

-- Expenses keep a copy of the people's emails, so deleting a user never loses financial history.
CREATE TABLE expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    department_id bigint NOT NULL,
    category_id bigint NOT NULL,
    amount numeric(14, 2) NOT NULL,
    currency character varying(3) NOT NULL,
    expense_date date NOT NULL,
    vendor character varying(120) NOT NULL,
    description character varying(500),
    reference character varying(80),
    status character varying(16) NOT NULL,
    over_budget boolean NOT NULL DEFAULT false,
    submitted_by_id bigint,
    submitted_by_email character varying(255) NOT NULL,
    submitted_at timestamp(6) without time zone,
    decided_by_id bigint,
    decided_by_email character varying(255),
    decided_at timestamp(6) without time zone,
    decision_note character varying(500),
    paid_on date,
    paid_by_email character varying(255),
    paid_at timestamp(6) without time zone,
    payment_reference character varying(80),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT expenses_pkey PRIMARY KEY (id),
    CONSTRAINT ck_expenses_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED', 'PAID')),
    CONSTRAINT ck_expenses_amount CHECK (amount > 0),
    CONSTRAINT fk_expenses_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_expenses_category FOREIGN KEY (category_id) REFERENCES expense_categories (id),
    CONSTRAINT fk_expenses_submitted_by FOREIGN KEY (submitted_by_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_expenses_decided_by FOREIGN KEY (decided_by_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_expenses_department_date ON expenses (department_id, expense_date);
CREATE INDEX ix_expenses_status ON expenses (status);
CREATE INDEX ix_expenses_paid_on ON expenses (paid_on);

-- A goal is a KPI with a target for one department and one quarter.
CREATE TABLE goals (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    department_id bigint NOT NULL,
    name character varying(120) NOT NULL,
    description character varying(500),
    unit character varying(20) NOT NULL,
    direction character varying(20) NOT NULL,
    baseline numeric(14, 2) NOT NULL,
    target numeric(14, 2) NOT NULL,
    weight integer NOT NULL DEFAULT 1,
    fiscal_year integer NOT NULL,
    fiscal_quarter integer NOT NULL,
    owner_id bigint,
    created_by character varying(255),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT goals_pkey PRIMARY KEY (id),
    CONSTRAINT ck_goals_direction CHECK (direction IN ('HIGHER_IS_BETTER', 'LOWER_IS_BETTER')),
    CONSTRAINT ck_goals_quarter CHECK (fiscal_quarter BETWEEN 1 AND 4),
    CONSTRAINT ck_goals_year CHECK (fiscal_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_goals_weight CHECK (weight BETWEEN 1 AND 100),
    CONSTRAINT ck_goals_target CHECK (target <> baseline),
    CONSTRAINT fk_goals_department FOREIGN KEY (department_id) REFERENCES departments (id),
    CONSTRAINT fk_goals_owner FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_goals_period ON goals (fiscal_year, fiscal_quarter);

-- Check-ins come from the UI, a CSV import or an integration (API key).
CREATE TABLE goal_checkins (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    goal_id bigint NOT NULL,
    checkin_date date NOT NULL,
    value numeric(14, 2) NOT NULL,
    note character varying(500),
    source character varying(10) NOT NULL,
    recorded_by_id bigint,
    recorded_by character varying(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT goal_checkins_pkey PRIMARY KEY (id),
    CONSTRAINT ck_goal_checkins_source CHECK (source IN ('UI', 'CSV', 'API')),
    CONSTRAINT fk_goal_checkins_goal FOREIGN KEY (goal_id) REFERENCES goals (id) ON DELETE CASCADE,
    CONSTRAINT fk_goal_checkins_recorded_by FOREIGN KEY (recorded_by_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX ix_goal_checkins_goal_date ON goal_checkins (goal_id, checkin_date);
