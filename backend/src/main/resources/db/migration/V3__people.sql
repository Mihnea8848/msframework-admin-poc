-- People management: department managers, last sign-in and job titles, audit subjects for the
-- activity feeds, access requests from self-registration, and the indexes the user search needs.
-- Never edit this file once applied. Add a new V<n>__description.sql instead.

-- Preflight for the case-insensitive unique email index below. The application has always stored
-- emails in lower case, but databases from before that rule may hold the same address twice with
-- different capitals. Stop with a clear message instead of an index error.
DO $$
DECLARE
    duplicates text;
BEGIN
    SELECT string_agg(email, ', ' ORDER BY email) INTO duplicates
    FROM (SELECT lower(email) AS email FROM users GROUP BY lower(email) HAVING count(*) > 1) d;
    IF duplicates IS NOT NULL THEN
        RAISE EXCEPTION 'These email addresses belong to more than one user (ignoring capitals): %. '
            'Merge or rename the duplicate accounts, then start the application again.', duplicates;
    END IF;
END $$;

-- users: job title and last successful sign-in
ALTER TABLE users ADD COLUMN title character varying(255);
ALTER TABLE users ADD COLUMN last_login_at timestamp(6) without time zone;

CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));
CREATE INDEX ix_users_department_id ON users (department_id);

-- departments: the head of the department (a member of it), cleared when that user is deleted
ALTER TABLE departments ADD COLUMN manager_id bigint;
ALTER TABLE departments
    ADD CONSTRAINT fk_departments_manager FOREIGN KEY (manager_id) REFERENCES users (id) ON DELETE SET NULL;
CREATE INDEX ix_departments_manager_id ON departments (manager_id);

-- audit_events: the user and department an event is about, for the per-user and per-department
-- activity feeds. No foreign keys: the history must outlive deleted users and departments.
ALTER TABLE audit_events ADD COLUMN subject_user_id bigint;
ALTER TABLE audit_events ADD COLUMN subject_department_id bigint;

CREATE INDEX ix_audit_events_created ON audit_events (created_at DESC, id DESC);
CREATE INDEX ix_audit_events_actor_created ON audit_events (actor_email, created_at DESC, id DESC);
CREATE INDEX ix_audit_events_subject_user ON audit_events (subject_user_id, created_at DESC, id DESC)
    WHERE subject_user_id IS NOT NULL;
CREATE INDEX ix_audit_events_subject_department ON audit_events (subject_department_id, created_at DESC, id DESC)
    WHERE subject_department_id IS NOT NULL;

-- access_requests: self-registrations waiting for an administrator. The password is stored as the
-- bcrypt hash the user account will get on approval, and is cleared once the request is decided.
CREATE TABLE access_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    full_name character varying(255) NOT NULL,
    email character varying(255) NOT NULL,
    phone character varying(255),
    department_id bigint,
    password_hash character varying(255),
    status character varying(16) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    decided_by character varying(255),
    decided_at timestamp(6) without time zone,
    note character varying(500),
    user_id bigint,
    CONSTRAINT access_requests_pkey PRIMARY KEY (id),
    CONSTRAINT ck_access_requests_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT fk_access_requests_department FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE SET NULL,
    CONSTRAINT fk_access_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

-- One open request per address; decided requests are kept as history.
CREATE UNIQUE INDEX ux_access_requests_pending_email ON access_requests (lower(email)) WHERE status = 'PENDING';
CREATE INDEX ix_access_requests_status_created ON access_requests (status, created_at DESC);
